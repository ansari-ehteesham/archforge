"""
This file is only for checking if the model is having the capability of calling the tool. This all the code is copied from the
Gemini Model.
"""


import os
from google import genai
from google.genai import types

def get_stock_price(ticker: str) -> str:
    """Gets the current stock price for a given ticker symbol.

    Args:
        ticker: The stock ticker symbol (e.g., 'GOOG', 'AAPL').
    """
    prices = {"GOOG": "$175.50", "AAPL": "$180.25", "MSFT": "$420.10"}
    price = prices.get(ticker.upper(), "unknown price")
    return f"The current price for {ticker.upper()} is {price}."

client = genai.Client()

# Initialize the chat session
chat = client.chats.create(
    model="gemini-3.5-flash-lite",
    config=types.GenerateContentConfig(
        tools=[get_stock_price],
        # FIXED: Pass "ANY" as a string instead of using a nonexistent Enum
        tool_config=types.ToolConfig(
            function_calling_config=types.FunctionCallingConfig(
                mode="ANY", # Options: "AUTO", "ANY", "NONE"
                allowed_function_names=["get_stock_price"]
            )
        )
    )
)

prompt = "Can you look up the stock price for GOOG?"
print(f"User Prompt: {prompt}\n")

response = chat.send_message(prompt)

print("--- Inspecting Intermediate Steps ---")

# Loop through the complete chat log generated by the exchange
for interaction in chat.get_history():
    role = interaction.role  # 'user' or 'model'
    
    for part in interaction.parts:
        if role == "user":
            if part.text:
                print(f"👤 User Sent Text: '{part.text}'")
            elif part.function_response:
                print(f"🔧 System Sent Tool Output back to Model:")
                print(f"   Function: {part.function_response.name}")
                print(f"   Payload:  {part.function_response.response}")
        
        elif role == "model":
            if part.function_call:
                print(f"🤖 Model Requested Tool Execution:")
                print(f"   Call Function: '{part.function_call.name}'")
                print(f"   Arguments:     {part.function_call.args}")
            elif part.text:
                print(f"🤖 Model Responded with Final Text: '{part.text}'")
    print("-" * 40)
